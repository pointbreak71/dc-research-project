const FONT = "Arial";
const border = { style: BorderStyle.SINGLE, size: 4, color: "CCCCCC" };
const borders = { top: border, bottom: border, left: border, right: border };
function runs(text, size) {
  // **bold** markup
  return String(text).split(/(\*\*[^*]+\*\*)/).filter(Boolean).map((s) =>
    s.startsWith("**")
      ? new TextRun({ font: FONT, text: s.slice(2, -2), bold: true, size })
      : new TextRun({ font: FONT, text: s, size }));
}
const P = (text, opts = {}) => new Paragraph({ spacing: { after: 120 }, ...opts, children: runs(text) });
const B = (text) => new Paragraph({ numbering: { reference: "bul", level: 0 }, spacing: { after: 80 }, children: runs(text) });
const H1 = (t) => new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun(t)] });
const H2 = (t) => new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun(t)] });
const Cap = (t) => new Paragraph({ spacing: { before: 60, after: 200 }, children: [new TextRun({ font: FONT, text: t, italics: true, size: 18, color: "555555" })] });

function table(header, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  const cell = (txt, i, isHead) => new TableCell({
    borders,
    width: { size: widths[i], type: WidthType.DXA },
    shading: isHead ? { fill: "E8EEF6", type: ShadingType.CLEAR } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [new Paragraph({ children: isHead ? [new TextRun({ font: FONT, text: txt, bold: true, size: 18 })] : runs(txt, 18) })],
  });
  return new Table({
    width: { size: total, type: WidthType.DXA },
    columnWidths: widths,
    rows: [
      new TableRow({ tableHeader: true, children: header.map((h, i) => cell(h, i, true)) }),
      ...rows.map((r) => new TableRow({ cantSplit: true, children: r.map((v, i) => cell(v, i, false)) })),
    ],
  });
}

